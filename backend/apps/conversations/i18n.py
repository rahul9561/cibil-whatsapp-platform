"""Bot messages in the customer's language: English (copy.py), Hindi, Punjabi, Telugu, Tamil.

`copy_for(language)` returns an object with the same names as copy.py; a name missing from a translation
falls back to English, so a new English message never breaks the bot before it is translated.

Rules for translators (checked by tests):
  * keep every {placeholder} exactly as in English;
  * keep the commands HI, CANCEL, STOP, START, HELP, LANGUAGE, and examples like ABCDE1234F, in English;
  * button titles: at most 20 characters; the button id (first item) never changes.

The translations are a first version and need review by native speakers before launch; the consent text
(CONSENT_TEXT and its CONSENT_*_LINE parts) needs legal review in every language.
"""

from . import copy as _en

LANGUAGE_CODES = ("en", "hi", "pa", "te", "ta")
# What the customer sees in the language menu (in their own script) and what they may type instead.
LANGUAGE_MENU = (
    ("en", "English"),
    ("hi", "हिंदी (Hindi)"),
    ("pa", "ਪੰਜਾਬੀ (Punjabi)"),
    ("te", "తెలుగు (Telugu)"),
    ("ta", "தமிழ் (Tamil)"),
)
# Never the bare codes: "hi" is a greeting, not a request for Hindi.
_TYPED = {
    "en": {"1", "english", "eng", "angrezi"},
    "hi": {"2", "hindi", "हिंदी", "हिन्दी"},
    "pa": {"3", "punjabi", "ਪੰਜਾਬੀ"},
    "te": {"4", "telugu", "తెలుగు"},
    "ta": {"5", "tamil", "தமிழ்"},
}
LANGUAGE_BUTTON_PREFIX = "lang_"
LANGUAGE_COMMANDS = {"LANGUAGE", "LANG", "BHASHA", "भाषा"}


def parse_language(reply_id: str | None, text: str) -> str | None:
    """Language code from a menu tap ("lang_hi") or typed text ("2", "hindi", "हिंदी"), else None."""
    if reply_id and reply_id.startswith(LANGUAGE_BUTTON_PREFIX):
        code = reply_id[len(LANGUAGE_BUTTON_PREFIX) :]
        return code if code in LANGUAGE_CODES else None
    typed = (text or "").strip().lower()
    return next((code for code, words in _TYPED.items() if typed in words), None)


